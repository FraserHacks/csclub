create table members (
	id bigint generated by default as identity primary key,
	name text not null default '',
	email text not null default '',
	grade int,
	github text not null default '',
	role text not null default '',
	exec boolean not null default false,
	projects text not null default '',
	hidden boolean not null default false,
	created_at timestamptz not null default now()
);
create index on members (email);

create table projects (
	id bigint generated by default as identity primary key,
	name text not null default '',
	description text not null default '',
	type text not null default 'hw' check (type in ('hw', 'sw', 'both')),
	image text not null default '',
	link text not null default '',
	meeting int,
	hidden boolean not null default false,
	member_ids bigint[] not null default '{}',
	frame text not null default '',
	created_at timestamptz not null default now()
);

create table entrants (
	id text primary key,
	email text not null unique,
	name text not null,
	skill text not null,
	characters text not null default '',
	controller boolean not null default false,
	at timestamptz not null default now()
);

-- Latest row is the live bracket, older rows are backups
create table brackets (
	id bigint generated always as identity primary key,
	bracket jsonb not null,
	entrants jsonb not null,
	created_at timestamptz not null default now()
);

alter table members enable row level security;
alter table projects enable row level security;
alter table entrants enable row level security;
alter table brackets enable row level security;

insert into storage.buckets (id, name, public) values ('projects', 'projects', true);
